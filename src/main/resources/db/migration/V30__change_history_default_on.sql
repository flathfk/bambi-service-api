    '변경점(Delta) 추적 리포트 계정 설정. true 면 생성 요청에 change_history_enabled 를 실어 보낸다. 기본 true(2026-08-12 V30 — 첫 보고서부터 델타를 보여주려고 opt-out 으로 전환. LLM 비용은 더 든다).';
