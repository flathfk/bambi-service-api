-- V22 에서 이 설정의 기본값을 FALSE 로 잡았다. 근거는 "델타 경로는 일반 생성보다 LLM 호출이
-- 많으니(팩트 추출·종합·파급효과) 비용 큰 경로는 사용자가 명시적으로 켠다"였다.
--
-- 그 판단을 뒤집는다. 이유는 **첫 보고서의 인상**이다.
--   · 가입 직후 받는 보고서가 델타 없이 나가면, 사용자가 설정을 켜기 전까지는
--     "지난번 이후 뭐가 달라졌나"라는 이 서비스의 핵심 값을 한 번도 못 본다.
--   · 그런데 그 설정은 /settings 안에 있어서 처음 온 사람이 찾아 켤 이유가 없다.
--   · 델타는 "주제를 처음 받는 경우에는 전체 내용으로" 동작한다 — 켜 둬도 첫 보고서가
--     망가지지 않는다. 두 번째부터 전/후 비교가 붙을 뿐이다.
--
-- 비용은 여전히 는다. 그 트레이드오프를 알고 켜는 것이고, 사용자는 언제든 끌 수 있다
-- (PATCH /api/users/me/settings).
--
-- ⚠️ 기존 사용자는 건드리지 않는다. 이미 값을 가진 계정을 일괄로 뒤집으면
--    끄기로 선택했던 사람의 설정까지 되돌리게 된다. 이 마이그레이션은 **앞으로 가입하는
--    계정의 기본값**만 바꾼다.
--
-- ⚠️ 엔티티 @Column 과 기본값 정합 필수:
--   change_history_enabled BOOLEAN DEFAULT TRUE ↔ User.changeHistoryEnabled = true
-- =============================================================

ALTER TABLE service.users
    ALTER COLUMN change_history_enabled SET DEFAULT TRUE;

